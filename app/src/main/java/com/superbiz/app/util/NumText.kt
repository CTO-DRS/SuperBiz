package com.superbiz.app.util

/**
 * [P7-L1 إصلاح] الموقع القياسي لتحليل أرقام حقول الإدخال (نص → Double).
 *
 * كان التنفيذ يسكن ui/components/Common.kt فكان استيراده من طبقات أدنى (vm)
 * خرقاً لاتجاه الطبقات (ui ← vm). الآن التنفيذ هنا في util (بلا أي اعتماد على
 * Android أو Compose)، وترك في ui.components.Common.kt alias مفوض بنفس التوقيع
 * حفاظاً على ~38 مستدعياً قائماً دون تغيير سطر واحد عندهم. الاستيراد الجديد
 * من أي طبقة يجب أن يكون من هنا وحده.
 */
object NumText {

    /**
     * [P7-L2 إصلاح] العقد الموثق لـ parseNum — تحليل متسامح لحقول الإدخال:
     *
     * - المدخل الفارغ/فراغات فقط ⇒ 0.0 (سلسلة منحلة تعني «حقل فارغ» وليس خطأً —
     *   الحقول الرقمية في المحررات تبدأ فارغة ويجب أن يُحفظ صفر بلا ضجيج).
     * - الأرقام العربية-الهندية ٠-٩ (U+0660..U+0669) والفارسية/الأردية ۰-۹
     *   (U+06F0..U+06F9) تُحوَّل إلى الغربية المقابلة.
     * - فاصل التجميع العربي ٬ (U+066C) والفاصلة الغربية , تُحذفان (فاصل آلاف).
     * - الفاصلة العشرية العربية ٫ (U+066B) تصير '.'.
     * - أي محرف آخر يُمرَّر كما هو إلى toDoubleOrNull، والفشل (حروف/رموز غريبة/
     *   صيغ غير رقمية) ⇒ 0.0 صامتاً **بلا استثناء وبلا تسجيل** — هذا مسار ساخن
     *   يُستدعى داخل recomposition وحلقات المحررات، فالتسجيل فيه ضجيج مقصود
     *   إيقافه؛ الطبقة العليا تتحقق من صحة القيمة بعد التحليل.
     * - السالب يُقبل ("-50" ⇒ −50.0) كما هو في toDoubleOrNull — تُقيَّد دلالياً
     *   عند المستدعي (مثل coerceIn في خصم السلة) لا هنا.
     *
     * أمثلة: "" ⇒ 0.0 · "abc" ⇒ 0.0 · "١٢٫٥" ⇒ 12.5 · "1,200" ⇒ 1200.0 · "-50" ⇒ −50.0
     */
    fun parseNum(s: String): Double {
        if (s.isBlank()) return 0.0
        val normalized = buildString(s.length) {
            for (c in s) {
                when {
                    c in '٠'..'٩' -> append(c - '٠')            // أرقام عربية-هندية → غربية
                    c in '۰'..'۹' -> append(c - '۰')            // أرقام فارسية/أردو (احتياط لوحة المفاتيح)
                    c == '٬' || c == ',' -> {}                   // فاصل الآلاف (عربي/غربي) — يُحذف
                    c == '٫' -> append('.')                      // الفاصلة العشرية العربية
                    else -> append(c)
                }
            }
        }.trim()
        return normalized.toDoubleOrNull() ?: 0.0
    }
}
