package com.superbiz.app.domain

/**
 * [P45-Q1] جولة 6 — تعميم التخصيص على أقسام شاشة التقارير.
 *
 * مرشح «الجولة القادمة» الموثق بعد P44: «تعميم التخصيص على عناصر شاشات
 * إضافية (ترتيب أقسام التقارير نفسها بنفس محرك DashboardPrefs)». هذا
 * الصندوق يعلن الأقسام القياسية (canonical) لشاشة التقارير بترتيبها
 * التاريخي، ويعيد استخدام محرك DashboardPrefsP44 **كما هو** بمفتاح شاشة
 * مستقل (`rep_sections`) داخل نفس خزنة `dashboard_layout` — لا مفتاح
 * DataStore جديد ولا ترحيل: المفاتيح المجهولة محفوظة أصلاً بعقد التوافق
 * الأمامي للمحرك (هبوط→ترقية لا يفقد تخصيص الأقسام).
 *
 * ─── العقود ───
 *  - القائمة القياسية ثابتة بترتيبها التاريخي — القسم الجديد مستقبلاً يُلحق
 *    آلياً بنهاية الترتيب (عقد effectiveOrder) بلا هجرة إعدادات.
 *  - الافتراضي (لا تفضيل مخزّن) = القائمة القياسية كاملة ظاهرة — الشاشة
 *    كما كانت حرفياً قبل الجولة.
 *  - الإخفاء يحفظ موضع القسم كي يعود إليه (عقد withToggle في المحرك).
 *  - الملف نقي بلا أي اعتماد Android — JUnit مجرد (نمط DashboardPrefsP44).
 */
object ReportSectionsP45 {

    /** مفتاح شاشة الأقسام داخل خزنة dashboard_layout المشتركة */
    const val KEY = "rep_sections"

    /** الأقسام القياسية الـ24 بترتيبها التاريخي — العقد المشترك مع الواجهة */
    val CANONICAL = listOf(
        "tools",         // بطاقة أدوات التصدير (A4/Excel/PDF)
        "periods",       // رقائق الفترات
        "categories",    // رقائق التصنيف (شرطية بوجود تصنيفات)
        "kpi",           // بطاقات المؤشرات المالية
        "summary",       // الملخص النصي القابل للنسخ
        "compare",       // مقارنة الشهرين (شرطية بوجود بيانات)
        "sales_expenses",// المبيعات والمصروفات
        "cashflow",      // التدفق النقدي
        "runway",        // المدرج النقدي وأيام السيولة
        "aging",         // أعمار الديون
        "hours",         // ساعات الذروة (شرطية)
        "vat_rates",     // الضريبة حسب النسبة
        "vat_return",    // تقرير الضريبة الدوري (الإقرار)
        "deep",          // الدفتر التفصيلي (P43)
        "customers",     // أفضل العملاء (شرطية)
        "products",      // أفضل المنتجات (شرطية)
        "margin",        // أعلى الربحية (شرطية)
        "trend",         // اتجاه المبيعات (شرطية)
        "smooth",        // التنعيم الأسي وإسقاط Holt
        "seasonality",   // الموسمية الشهرية
        "concentration", // تركّز العملاء
        "breakeven",     // نقطة التعادل (شرطية)
        "trial",         // ميزان المراجعة
        "insights",      // بطاقات الذكاء (مكدس P44 المخصص ذاته)
    )

    /** الترتيب الفعّال لأقسام التقارير من السلسلة الخام — راحة على المحرك المشترك */
    fun order(raw: String?): List<String> =
        DashboardPrefsP44.effectiveOrder(KEY, CANONICAL, raw)
}
