package com.superbiz.app.domain

/**
 * ═══════════════════════════════════════════════════════════════════════════
 * [RVW-4 V 3.2.2] إشارة قفل التطبيق على مستوى العملية + قرار خصوصية الويدجات
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * المشكلة الموثقة (مراجعة ما قبل الدمج المستقلة — خطر 6): القفل شاشة Compose
 * داخل MainActivity فقط، فلا يعرف مستهلك خارج تركيبة الواجهة (الويدجات خصوصاً)
 * هل التطبيق مقفل أم لا — كانت الويدجات تعرض المبالغ المالية (نقد/مبيعات/ذمم)
 * والتطبيق مقفل ما لم يفعّل المالك تفضيل «إخفاء الأرقام» يدوياً.
 *
 * الحل: إشارة عملية صريحة يضبطها MainActivity لحظة فتح القفل وعند كل إعادة
 * قفل (فوري أو بمهلة)، وقرار إخفاء موحّد نقي قابل للاختبار JVM بلا Android:
 *  • تفضيل المالك (redactWidgets) يحسم الإخفاء دائماً — كما كان.
 *  • الإضافة: وجود وسيلة حماية (رمز/بصمة) مع تطبيق غير مفتوح ⇒ إخفاء حتى
 *    بلا تفضيل — الويدجت على الشاشة الرئيسية مرئية للناظرين بلا أي قفل،
 *    والقفل الوحيد كان يحمي فتح التطبيق لا قراءة أرقامه من الويدجت.
 *  • بلا وسيلة حماية: السلوك التاريخي حرفياً (لا إخفاء إضافي).
 *  • الافتراض fail-closed: قيمة unlocked تبدأ false وتعود false عند كل
 *    إعادة قفل/موت عملية — فأي رسم ويدجة في نافذة شك يعرض القناع لا الأرقام.
 *
 * وحدة JVM خالصة بلا أي اعتماد Android — على نمط محركات domain النقية.
 */
object AppLockSignal {

    /**
     * هل التطبيق مفتوح فعلاً في الواجهة الآن؟ يضبطه MainActivity:
     * true عند نجاح فتح القفل (onUnlocked)، وfalse عند كل إعادة قفل
     * (ON_STOP الفوري، وعند تجاوز مهلة إعادة القفل في ON_START).
     * الافتراض false يغطي الإقلاع البارد للعملية وموت العملية — فشل مغلق.
     */
    @Volatile
    var unlocked: Boolean = false

    /** هل توجد وسيلة حماية مهيأة؟ (رمز PIN مُدخل أو بصمة مفعّلة) — نفس شرط MainActivity الحرفي */
    fun lockConfigured(pinHash: String?, pinBlob: String?, biometric: Boolean): Boolean =
        pinHash != null || pinBlob != null || biometric

    /**
     * قرار الإخفاء الموحد للويدجات — الدالة النقية الوحيدة التي يمر منها العرض:
     *  1) تفضيل الإخفاء الصريح يحسم (أعلى أولوية — إرادة المالك).
     *  2) قفل مهيأ + تطبيق غير مفتوح = إخفاء (الإضافة الجديدة).
     *  3) بلا قفل مهيأ: لا إخفاء إضافي أبداً (سلوك تاريخي محفوظ).
     */
    fun shouldRedactWidgets(prefRedact: Boolean, lockConfigured: Boolean): Boolean =
        prefRedact || (lockConfigured && !unlocked)
}
