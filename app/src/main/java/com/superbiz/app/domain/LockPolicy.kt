package com.superbiz.app.domain

/**
 * [RVW-11 V 3.2.3] سياسة القفل النقية — تثبيت عقد «لا بيومتريا بلا رمز» كعقد
 * قابل للتنفيذ لا سطر UI قابل للانجراف.
 *
 * الخطر 3 في FINDINGS §2: مسار «متابعة (طارئ)» في شاشة القفل يفتح جلسة
 * المالك بنقرة واحدة حين `biometricOn && !bioReady && !hasPin` (جهاز أحادي
 * المالك). البوابة **الوقائية** قائمة منذ موجة P5-H4 في شاشة الإعدادات
 * (تعذير التبديل بلا PIN) وفي المسار لكل مستخدم (`setBiometricAllowed`
 * يشترط `pinWrapped` قائماً) — لكنها كانت شرطاً حراً داخل Composable بلا
 * اختبار يثبّته. هنا العقد بصيغة نقية: تمكين البصمة يتطلب رمز قفل مُعداً.
 *
 * المسار الطارئ القائم يبقى كما هو عمداً: يخدم الأجهزة التي فعّلت البصمة
 * قبل بوابة P5-H4 (حالة قديمة لا يمكن توليدها جديدة)، وإزالته يُقصي مستخدم
 * الحساس المكسور نهائياً — القرار الموثق في FINDINGS §2/§5 (RVW-11).
 * JVM خالص — نمط محرك domain النقي.
 */
object LockPolicy {

    /**
     * هل يجوز تمكين تسجيل البصمة؟ [pinConfigured] = يوجد رمز قفل مُعد
     * (pinHash أو pinBlob للمالك، أو pinWrapped لمستخدم صريح).
     * الفشل مغلق: بلا رمز ⇒ ممنوع.
     */
    fun canEnableBiometric(pinConfigured: Boolean): Boolean = pinConfigured
}
