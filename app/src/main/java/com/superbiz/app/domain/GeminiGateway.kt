package com.superbiz.app.domain

/**
 * [F2 - ADR-005 D4] الواجهة النقية الثانية التي تعبر حدود ADR-001 نحو طبقة
 * الشبكة — عقد المحسّر السحابي المقفول (Gemini API) لتحسين نص OCR.
 *
 * ─── بنود D4 المنفَّذة حول هذا العقد حرفيًا ───
 * - **باب واحد بتفعيل صريح**: لا نداء لهذه الواجهة قبل تفعيل المالك في
 *   الإعدادات (GeminiAiStore — false افتراضيًا) وبتوفير مفتاح API مخزَّن
 *   مشفَّرًا — ناقص أيهما ⇒ TransientFailure بلا أي محاولة اتصال (فشل مغلق
 *   بلا رسالة سحابية زائفة).
 * - **قراءة قبل كل إرسال**: النص المرسل يُعرض على المالك ويُقر ويُؤكَّد في
 *   الواجهة قبل كل نداء — لا إرسال خلفي صامت لبيانات مالية أبدًا، ولا قائمة
 *   انتظار ولا WorkWorker: النداء هنا يدوي أحادي حصرًا.
 * - **ما يُرسل محصور**: نص OCR الخام فقط (يُقصّ للحد الصلب في طبقة النقل)
 *   + تعليمة إصلاح ثابتة — لا شيء من قاعدة البيانات المحلية إطلاقًا.
 * - **المخرج لا يُعتمد ماليًا**: النص العائد يمر حصرًا عبر OcrInvoiceParser
 *   النقي المحلي — كل المال يُعاد حسابه محليًا بقروش Long عبر المسار القانوني.
 *
 * ─── دلالة النتائج الثلاث (نمط ZatcaGateway نفسه) ───
 * - [GatewayResult.Accepted]: نجح الإرسال — النص المحسَّن جاهز لإعادة التحليل المحلي.
 * - [GatewayResult.Rejected]: رفض نهائي لا يُعاد بمجرده (مفتاح غير صالح،
 *   موديل غير موجود، حجب سلامة) — السبب يُعرض للمالك حرفيًا.
 * - [GatewayResult.TransientFailure]: عابر (شبكة/خادم/حد معدل/رد مشوه/الباب
 *   مقفول) — إعادة المحاولة مشروعة.
 *
 * النقية كاملة: الواجهة تعمل على JVM بلا أندرويد، والتنفيذ الوحيد يعيش في
 * حزمة `network` المعزولة (GeminiOcrClient) بلا أي مستدعٍ خارج التوصيل الجذري.
 */
interface GeminiGateway {

    companion object {
        /**
         * الموديل الافتراضي — ثابت في domain (لا data-layer تلمس حزمة network)
         * ويعدّله المالك نصًا حرًا من الإعدادات (اسم يُمرَّر كما هو، فارغ ⇒ هذا الافتراضي).
         */
        const val MODEL_DEFAULT = "gemini-2.5-flash"
    }

    /** طلب تحسين — نص OCR الخام كما خرج من محرك الجهاز (ML Kit) */
    data class EnhanceRequest(val rawOcrText: String)

    sealed class GatewayResult {
        /** نجح — النص المحسَّن (يُعاد تحليله محليًا حصرًا، لا يُعتمد ماليًا مباشرة) */
        data class Accepted(val text: String) : GatewayResult()

        /** رفض نهائي — السبب يُعرض للمالك حرفيًا، إعادة المحاولة بلا فائدة */
        data class Rejected(val reason: String) : GatewayResult()

        /** عابر — شبكة/خادم/حد معدل/رد مشوه/الباب مقفول؛ إعادة المحاولة مشروعة */
        data class TransientFailure(val message: String) : GatewayResult()
    }

    /** نداء التحسين الأحادي — يدوي حصرًا بعد قراءة المالك وتأكيده، بلا خلفية أبدًا */
    suspend fun enhance(request: EnhanceRequest): GatewayResult
}
