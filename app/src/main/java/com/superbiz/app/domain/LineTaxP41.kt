package com.superbiz.app.domain

/**
 * [P41-L1] جولة 2 — الحقول الضريبية على مستوى السطر + تمييز صفرية/معفاة (مخطط v11).
 *
 * هذا هو المحرك النقي الذي وثّقت P38 تأجيله: «الصفرية موحدة مع المعفاة (البيانات
 * لا تميّزهما — التمييز يحتاج حقولاً جديدة)». v11 يضيف عمودين إلى invoice_items
 * (`taxKind` فئة السطر و `taxRate` نسبة السطر الصريحة) ويجعل هذا الصندوق مصدر
 * الحقيقة الوحيد لرياضيات الضريبة على مستوى السطر — يستخدمه الحفظ، والتقرير
 * الضريبي، وXML القانوني حتى لا تتناقض المحجوز مع المعلن أبداً.
 *
 * ─── عقد التوافق (غير قابل للتفاوض) ───
 * - الصفوف القديمة (كل السطور الموجودة قبل v11) تأتي بـ(kind=0, rate=-1) من
 * بذرتَي الترحيل — أي لا سطر صريح ⇒ **المسار التاريخي الحرفي**: ضريبة الفاتورة
 * كاملة round(الصافي × النسبة / 100) على مستوى الرأس كما منذ — لا
 * إعادة توزيع ولا إعادة تقريب لسطر قديم أبداً.
 * - المسار الواعي بالسطر يُفتح فقط إن حمل **أي** سطر بياناً صريحاً (فئة غير
 * قياسية أو نسبة ≥ 0) — وحينها الضريبة = مجموع ضرائب الأسطر، وكل سطر قياسي
 * بلا نسبة صريحة يورّث النسبة المحفوظة في رأس الفاتورة (إعداد المنشأة لحظة
 * الإصدار).
 * - الصفرية (Z) والمعفاة (E) ضريبتها صفر دائماً — الفرق محاسبي وتقريري (خانتا
 * إقرار منفصلتان في ZatcaReturnP38) لا حسابي.
 * - التقريب نفسه منذ P33-P8: Math.round(net × rate / 100) — نصف الوحدة للأعلى
 * على القروش الموجبة، مطابق لحرف محرر الفاتورة ونقطة البيع.
 * - الملف نقي بلا أي اعتماد Android — JUnit مجرد (نمط ZatcaReturnP38).
 *
 * [P42-R3] جولة 3 — تفعيل النسبة الصريحة للسطر في المحرر (القرار المؤجل الموثق
 * في P41: «جاهزة في المحرك والمخطط ولا يتعرض لها المحرر عمداً»). تفعيلها هنا
 * لا يمس هذا الملف إلا بمدخل واحد صغير parseExplicitRate الذي يحوّل نص حقل
 * المحرر إلى قيمة معلنة بعقد الحصر نفسه — فبقي المحرك مصدر الحقيقة الوحيد
 * للحفظ والتقرير وXML كما هو منذ P41 بلا أي تغيير في العقود القائمة.
*/
object LineTaxP41 {

    /** فئة السطر: قياسية (خاضعة بالنسبة) — الافتراضية ودلالة كل الصفوف التاريخية */
    const val KIND_STANDARD = 0

    /** فئة السطر: صفرية — خاضعة بنسبة 0% (خانة إقرار مستقلة عن المعفاة منذ v11) */
    const val KIND_ZERO = 1

    /** فئة السطر: معفاة — خارج نطاق الضريبة (خانة إقرار مستقلة عن الصفرية منذ v11) */
    const val KIND_EXEMPT = 2

    /** قيمة taxRate الدالة على «وراثة النسبة من رأس الفاتورة (إعداد المنشأة)» */
    const val RATE_INHERIT = -1.0

    /** معرف فئة UBL المبسّط — العقد المشترك مع ZatcaInvoiceXml (S/Z/E) */
    fun categoryId(kind: Int): String = when (kind) {
        KIND_ZERO -> "Z"
        KIND_EXEMPT -> "E"
        else -> "S"
    }

    /**
     * [Z2-ب V 1.5.0] ترتيب الفئات الثابت للتجميع والعرض: S ثم Z ثم E —
     * حتمي مهما كان ترتيب الأسطر (يستهلكه ZatcaUbl.taxSubtotal كي تبقى
     * المستندات الذهبية بايتاً ببايت مستقلة عن ترتيب إدخال البنود).
     */
    fun order(kind: Int): Int = when (kind) {
        KIND_STANDARD -> 0
        KIND_ZERO -> 1
        else -> 2
    }

    /**
     * [P42-R3] جولة 3 — نص حقل «نسبة السطر» في المحرر → القيمة المعلنة.
     *
     * العقد (نفس حروف effectiveRate الدفاعية):
     *  - نص فارغ أو أبيض ⇒ null (⇒ يستدعي المتصل RATE_INHERIT — وراثة نسبة الرأس
     *    والسلوك التاريخي الحرفي كما لو لم يُكتب شيء).
     *  - غير الرقمي ⇒ null (لوحة الأرقام تمنعه غالباً — حرس دفاعي لا سياسة).
     *  - السالب ⇒ null — السالب عقد البذرة الدال على الوراثة ولا يجوز أن يفتح
     *    مسار السطر من طرف المستخدم.
     *  - الفاصلة «,» تُقبل فاصلاً عشرياً (لوحة الأرقام العربية).
     *  - خارج 0..100 يُحصر (الصفر صريح 0.0 ويفتح مسار السطر بعقد isExplicit).
     */
    fun parseExplicitRate(text: String): Double? {
        val t = text.trim()
        if (t.isEmpty()) return null
        val d = t.replace(',', '.').toDoubleOrNull() ?: return null
        if (d < 0.0) return null
        return d.coerceIn(0.0, 100.0)
    }

    /** هل السطر يحمل بياناً ضريبياً صريحاً (فئة غير قياسية أو نسبة معلنة)؟ */
    fun isExplicit(kind: Int, rate: Double): Boolean =
        kind != KIND_STANDARD || rate >= 0.0

    /** هل المجموعة واعية بالسطر؟ أي سطر صريح واحد يفتح مسار السطر للفاتورة كلها */
    fun isLineAware(lines: List<Pair<Int, Double>>): Boolean =
        lines.any { (k, r) -> isExplicit(k, r) }

    /**
     * النسبة الفعالة للسطر: الصفرية/المعفاة ⇒ 0.0 بلا استثناء؛ القياسية الصريحة
     * (أي قيمة ≥ 0) ⇒ نسبتها المعلنة؛ وإلا (أي سالب — والعقد الرسمي RATE_INHERIT
     * = -1.0 وهو ما تكتبه بذرة الترحيل) ⇒ وراثة نسبة الرأس (إعداد المنشأة).
     * النسبة المعلنة خارج 0..100 تُحصر (حرس دفاعي — المنتقي لا يمرر غيرها).
     */
    fun effectiveRate(kind: Int, rate: Double, settingsRate: Double): Double = when {
        kind == KIND_ZERO || kind == KIND_EXEMPT -> 0.0
        rate >= 0.0 -> rate.coerceIn(0.0, 100.0)
        else -> settingsRate
    }

    /**
     * ضريبة السطر بالقروش — نفس حرف الحفظ التاريخي Math.round(net × rate / 100)
     * على النسبة الفعالة للسطر.
     */
    fun lineTax(lineNet: Long, kind: Int, rate: Double, settingsRate: Double): Long =
        Math.round(lineNet * effectiveRate(kind, rate, settingsRate) / 100.0)

    /**
     * ضريبة الفاتورة من أسطرها — null إن لم يوجد أي سطر صريح (⇒ يستدعي المسار
     * التاريخي على مستوى الرأس ولا يُلمس السلوك القديم إطلاقاً).
     *
     * @param lineNets صافي كل سطر بعد خصمه (قروش)
     * @param kinds    فئة كل سطر (KIND_*)
     * @param rates    نسبة كل سطر المعلنة (RATE_INHERIT للوراثة)
     * @param settingsRate نسبة الرأس — إعداد المنشأة لحظة الإصدار
     */
    fun invoiceTaxFromLines(
        lineNets: List<Long>,
        kinds: List<Int>,
        rates: List<Double>,
        settingsRate: Double,
    ): Long? {
        if (lineNets.size != kinds.size || lineNets.size != rates.size) return null
        if (!isLineAware(lineNets.indices.map { kinds[it] to rates[it] })) return null
        return lineNets.indices.sumOf { lineTax(lineNets[it], kinds[it], rates[it], settingsRate) }
    }
}
