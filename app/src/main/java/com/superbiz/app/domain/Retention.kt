package com.superbiz.app.domain

/**
 * ═══════════════════════════════════════════════════════════════════════════
 * [RVW-6 V 3.2.2] سياسات حصر النمو — ثوابت وبوابات قرارات موثقة قابلة للاختبار النقي
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * الخطر الموثق (مراجعة ما قبل الدمج المستقلة — خطر 7): sync_log ينمو بلا سقف
 * على الأجهزة التي لا تفعّل المزامنة قط (27 مشغّلاً مركّباً للجميع منذ ترحيل
 * 15→16)، وaudit_log إلحاق خالص بلا أي سقف تخزين.
 *
 * العقود المحفوظة حرفياً:
 *  • جهاز مزامنته مفعّلة أو سبق أن أكمل دفعة كاملة: يُترك للعقد القائم —
 *    markPushed يقلم المعلّق (imported=0) بعد كل دفعة ناجحة، والشواهد
 *    (imported=1) قرار مالك موثق لا يُمس آلياً (صحة المزامنة أولاً).
 *  • audit_log يظل «إلحاق فقط» بمعناه التشغيلي: لا تعديل ولا إعادة ترتيب
 *    ولا مسّ بصفوف حية — الحذف الأقدم فحسب عند تجاوز سقف كريم سياسة
 *    تخزين موثقة (سجل قراءة تشغيلية لا أرشيف قانوني بلا حدود).
 */
object Retention {

    /**
     * سقف صفوف audit_log — يُحفظ الأحدث ويُحذف الأقدم فحسب. 50,000 صف
     * أعوام من الاستخدام الفعلي (أحداث الكشوف والإرسال والقواعد والدخول)،
     * والسقف موجود ليكون النمو محصوراً لا ليوفر مساحة.
     */
    const val AUDIT_KEEP_ROWS: Int = 50_000

    /**
     * بوابة تقليم دفتر المزامنة: يُقلَّم فقط حين لا توجد مزامنة مفعّلة الآن
     * **و**لم يُكمل هذا الجهاز دفعة كاملة قط (fullPushed=false). في هذه الحالة
     * الصفوف المعلّقة (imported=0) عبء ميت بلا مستهلك: لا جهاز آخر استهلك
     * بيانات هذا الجهاز قط، وعند تفعيل المزامنة لاحقاً يبدأ الدفع بمسح كامل
     * (fullPushed=false) فيغطي البيانات الحية دون حاجة للدفتر. أي مزاج آخر
     * (مفعّلة الآن، أو سبق الدفع الكامل) يُبقي الدفتر كما هو — لا مخاطرة
     * انحراف دلتا.
     */
    fun pruneSyncLedger(syncEnabled: Boolean, fullPushed: Boolean): Boolean =
        !syncEnabled && !fullPushed
}
